def build_dataloaders_for_phase(train_samples, val_samples, phase: str):
    """
    Filtra i campioni se necessario (per p2 e p3 solo tiri) e istanzia i DataLoader.
    """
    p_cfg = PHASE_CONFIGS[phase]
    
    if p_cfg["filter_shots_only"]:
        train_filtered = [s for s in train_samples if s["label"] in [1, 2, 3, 4, 5, 6]]
        val_filtered = [s for s in val_samples if s["label"] in [1, 2, 3, 4, 5, 6]]
    else:
        train_filtered = train_samples
        val_filtered = val_samples

    train_dataset = ActionRecognitionDataset(samples=train_filtered, is_feature_dataset=True)
    val_dataset = ActionRecognitionDataset(samples=val_filtered, is_feature_dataset=True)

    train_loader = DataLoader(
        train_dataset,
        batch_sampler=BucketSampler(
            sequence_lengths=[s["num_frames"] for s in train_filtered],
            batch_size=8
        ),
        collate_fn=pad_and_collate_video_batch
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=8,
        shuffle=False,
        collate_fn=pad_and_collate_video_batch
    )

    target_key = f"label_{phase}"
    train_phase_labels = [train_dataset[i][target_key] for i in range(len(train_dataset))]
    class_weights = compute_class_weights(
        train_phase_labels, 
        num_classes=p_cfg["num_classes"], 
        method="inverse"
    )

    return train_loader, val_loader, class_weights


def train_single_phase(
    phase: str,
    experiment_name: str,
    exp_dir: str, 
    config: dict,
    train_loader: DataLoader,
    val_loader: DataLoader,
    class_weights: torch.Tensor,
    device: torch.device,
    epochs: int,
    patience: int,
):
    p_cfg = PHASE_CONFIGS[phase]
    num_classes = p_cfg["num_classes"]

    phase_dir = os.path.join(exp_dir, phase)
    plots_dir = os.path.join(phase_dir, "plots")
    checkpoints_dir = os.path.join(phase_dir, "checkpoints")
    os.makedirs(plots_dir, exist_ok=True)
    os.makedirs(checkpoints_dir, exist_ok=True)

    print(f"\n{'='*70}")
    print(f"   STARTING PHASE: {p_cfg['name']} | Experiment: {experiment_name}")
    print(f"{'='*70}")

    keys, values = zip(*config["grid"].items())
    combinations = [dict(zip(keys, v)) for v in itertools.product(*values)]

    phase_results = []

    for run_idx, params in enumerate(combinations):
        run_id = run_idx + 1
        print(f"\n--> [{phase.upper()} | Run {run_id}/{len(combinations)}] Config: {params}")

        tb_logger = ExperimentLogger(
            log_dir=os.path.join(phase_dir, "tb_runs"),
            experiment_name=experiment_name,
            run_id=run_id,
        )

        neck = config["components"]["neck"](params, in_dim=FEATURE_DIM)
        head = config["components"]["head"](
            params,
            in_dim=neck.out_dim if hasattr(neck, "out_dim") else FEATURE_DIM,
            num_classes=num_classes,
        )
        criterion = config["components"]["loss"](params, class_weights.to(device))

        model = ARPipeline(backbone=None, neck=neck, head=head).to(device)
        optimizer = torch.optim.Adam(model.parameters(), lr=params.get("lr", 1e-3))

        best_run_f1 = -1.0
        best_run_acc = 0.0
        best_run_epoch = 0
        epochs_without_improvement = 0

        best_preds, best_labels = [], []
        label_key = f"label_{phase}"

        epoch_pbar = tqdm(
            range(1, epochs + 1),
            desc=f"[{phase.upper()} | Run {run_id}/{len(combinations)}]",
            unit="ep",
            leave=True
        )

        for epoch in epoch_pbar:
            # --- TRAINING ---
            model.train()
            train_loss = 0.0

            for batch in train_loader:
                x = batch["x"].to(device)
                labels = batch[label_key].to(device)
                lengths = batch["lengths"]

                optimizer.zero_grad()
                logits = model(x, lengths=lengths)
                loss = criterion(logits, labels)

                loss.backward()
                optimizer.step()

                train_loss += loss.item()

            # --- VALIDATION ---
            model.eval()
            all_preds, all_labels = [], []
            val_loss = 0.0

            with torch.no_grad():
                for batch in val_loader:
                    x = batch["x"].to(device)
                    labels = batch[label_key].to(device)
                    lengths = batch["lengths"]

                    logits = model(x, lengths=lengths)
                    loss = criterion(logits, labels)
                    val_loss += loss.item()

                    preds = torch.argmax(logits, dim=1)
                    all_preds.extend(preds.cpu().numpy())
                    all_labels.extend(labels.cpu().numpy())

            acc = accuracy_score(all_labels, all_preds)
            macro_f1 = f1_score(all_labels, all_preds, average="macro", zero_division=0)
            avg_train_loss = train_loss / len(train_loader)
            avg_val_loss = val_loss / len(val_loader)

            tb_logger.log_epoch(
                epoch=epoch,
                train_loss=avg_train_loss,
                val_loss=avg_val_loss,
                val_acc=acc,
                val_f1=macro_f1,
            )

            epoch_pbar.set_postfix({
                "TrLoss": f"{avg_train_loss:.4f}",
                "ValLoss": f"{avg_val_loss:.4f}",
                "ValAcc": f"{acc:.4f}",
                "ValF1": f"{macro_f1:.4f}",
                "BestF1": f"{best_run_f1:.4f}" if best_run_f1 > 0 else "N/A"
            })

            if macro_f1 > best_run_f1:
                best_run_f1 = macro_f1
                best_run_acc = acc
                best_run_epoch = epoch
                epochs_without_improvement = 0

                best_preds = all_preds
                best_labels = all_labels

                weight_path = os.path.join(
                    checkpoints_dir, f"{experiment_name}_run{run_id}_{phase}_best.pt"
                )
                torch.save(model.state_dict(), weight_path)
            else:
                epochs_without_improvement += 1

                if epochs_without_improvement >= patience:
                    epoch_pbar.write(
                        f"    [EARLY STOPPING - {phase.upper()}] Best Ep: {best_run_epoch} | Best Macro-F1: {best_run_f1:.4f}"
                    )
                    break

        if best_preds and best_labels:
            plot_path = os.path.join(
                plots_dir, f"{experiment_name}_run{run_id}_{phase}_cm.png"
            )
            phase_class_names = PHASE_CLASS_NAMES.get(phase, CLASS_NAMES)

            save_confusion_matrix_plot(
                best_labels,
                best_preds,
                plot_path,
                class_names=phase_class_names,
            )
            cm_tensor = get_confusion_matrix_tensor(
                best_labels, best_preds, class_names=phase_class_names
            )
            tb_logger.log_image(
                f"Confusion_Matrix/{phase.upper()}_Best",
                cm_tensor,
                step=best_run_epoch,
            )

        tb_logger.close()

        run_record = {
            "phase": phase,
            "experiment_name": experiment_name,
            "run_id": run_id,
            "hyperparameters": str(params),
            "best_epoch": best_run_epoch,
            "val_accuracy": round(best_run_acc, 4),
            "val_macro_f1": round(best_run_f1, 4),
            "checkpoint_path": os.path.join(checkpoints_dir, f"{experiment_name}_run{run_id}_{phase}_best.pt"),
            "confusion_matrix_path": os.path.join(plots_dir, f"{experiment_name}_run{run_id}_{phase}_cm.png"),
        }
        phase_results.append(run_record)

        del model, optimizer
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    return phase_results


