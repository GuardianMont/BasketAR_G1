def load_preextracted_features(pt_file_path: str):
    """
    Loads the .pt file generated by extract_features_offline.
    If the file does not exist, automatically creates a mock .pt feature dataset 
    for testing.
    """
    if not os.path.exists(pt_file_path):
        print(f"[WARNING] Feature file '{pt_file_path}' not found. Generating mock features for testing...")
        os.makedirs(os.path.dirname(pt_file_path), exist_ok=True)
        
        num_samples = 12 if "train" in pt_file_path else 6
        mock_samples = []
        
        for i in range(num_samples):
            T_i = int(torch.randint(8, 41, (1,)).item())
            mock_samples.append({
                "id": f"clip_{i:06d}",
                "data": torch.randn(T_i, 965),
                "label": i % 9,
                "num_frames": T_i
            })
            
        mock_payload = {
            "format_version": 1,
            "backbone": "MockBackbone",
            "feature_dim": 965,
            "num_samples": num_samples,
            "samples": mock_samples
        }
        
        torch.save(mock_payload, pt_file_path)
        print(f"[INFO] Created mock dataset file at '{pt_file_path}' with {num_samples} samples.")
    
    payload = torch.load(pt_file_path, map_location="cpu", weights_only=False)
    print(f"[INFO] Loaded {payload['num_samples']} features (Dimension D={payload['feature_dim']}) from '{pt_file_path}' (Backbone: {payload['backbone']})")
    
    return payload["samples"]


